/**
 * Academic Export Utility for AI Study Companion
 * Provides clean downloads for Markdown, Anki-compatible Flashcard Decks,
 * and Print-Ready Academic Examination Papers and Notes.
 */

// Helper to download raw text files
export function downloadFile(filename: string, content: string, mimeType = 'text/plain;charset=utf-8') {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

// 1. Export Markdown file
export function exportToMarkdown(filename: string, markdownContent: string) {
  const safeFilename = filename.endsWith('.md') ? filename : `${filename}.md`;
  downloadFile(safeFilename, markdownContent, 'text/markdown;charset=utf-8');
}

// 2. Export Flashcard deck to Anki-compatible format (.txt / .csv)
export interface ExportCardItem {
  front: string;
  back: string;
}

export function exportFlashcardsToAnki(deckTitle: string, cards: ExportCardItem[]) {
  const safeTitle = deckTitle.trim().replace(/[^a-zA-Z0-9_-]/g, '_');
  
  // Format for Anki (Tab-separated with standard headers)
  let output = `#separator:tab\n#html:false\n#deck:${deckTitle}\n#tags:AI_Study_Companion\n`;
  
  for (const card of cards) {
    // Escape internal tabs and newlines for clean Anki row import
    const front = card.front.replace(/\t/g, ' ').replace(/\n/g, '<br>');
    const back = card.back.replace(/\t/g, ' ').replace(/\n/g, '<br>');
    output += `${front}\t${back}\n`;
  }

  downloadFile(`${safeTitle}_anki_deck.txt`, output, 'text/tab-separated-values;charset=utf-8');
}

